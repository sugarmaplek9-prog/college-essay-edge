a("    taxonomy_version: 'taxonomy_v1',");
a("    made_at: new Date().toISOString(),");
a("    made_by: 'classifier',");
a("  };");
a("  return {");
a("    usable_signal: usable,");
a("    signal_strength: strength,");
a("    signal_types: types,");
a("    confidence,");
a("    reason_codes,");
a("    evidence_sources,");
a("    meta,");
a("  };");
a("}");

