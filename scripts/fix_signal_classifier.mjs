a("  /i (realized|noticed) (that )?i (had been|was) (removing|excluding|not including)/i,");
a("  /solving (it|the problem) alone (was|started)/i,");
a("  /i had been (making|taking) decisions (without|alone|by myself)/i,");
a("  /i brought (the team|everyone|others) in/i,");
